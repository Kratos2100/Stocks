"""Command line interface.

Examples::

    python -m options_mas.cli synthetic --out data/synthetic --sessions 20
    python -m options_mas.cli backtest --synthetic --agents A01 --out reports/a01.json
    python -m options_mas.cli backtest --data data/options.csv --label "VENDOR_X 2025" \
        --underlying data/index.csv --chains data/chains.csv
    python -m options_mas.cli walkforward --synthetic --agents A02 \
        --grid agent02.ema_period=7,9,11 --train 8 --test 4
    python -m options_mas.cli sensitivity --synthetic --param agent01.entry_offset --values 1,2,3
    python -m options_mas.cli paper --synthetic --mode paper
    python -m options_mas.cli dashboard --synthetic --port 8000
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
from datetime import datetime
from pathlib import Path

from .config import AppConfig, load_config
from .models import DeltaSource


def _val(s: str):
    for f in (int, float):
        try:
            return f(s)
        except ValueError:
            pass
    if s.lower() in ("true", "false"):
        return s.lower() == "true"
    if s.lower() == "none":
        return None
    return s


def _dataset(args, cfg: AppConfig):
    if getattr(args, "synthetic", False) or not getattr(args, "data", None):
        from .data.synthetic import generate_synthetic_dataset
        print("[data] generating SYNTHETIC dataset – results are NOT real market performance", file=sys.stderr)
        return generate_synthetic_dataset(sessions=args.sessions, seed=args.seed,
                                          with_subbars=getattr(args, "subbars_synthetic", False))
    from .data.dataset import load_dataset
    lots = {k: v.lot_size for k, v in cfg.instruments.items()}
    src = DeltaSource(args.delta_source) if args.delta_source else None
    return load_dataset(args.data, lots, timeframe_min=cfg.session.timeframe_min, subbars_path=args.subbars,
                        underlying_path=args.underlying, chains_path=args.chains, label=args.label,
                        default_delta_source=src)


def _common(p: argparse.ArgumentParser) -> None:
    p.add_argument("--config", help="TOML config file")
    p.add_argument("--data", help="long-format option candles CSV/Parquet")
    p.add_argument("--subbars", help="optional 1-minute option candles for intrabar refinement")
    p.add_argument("--underlying", help="optional underlying candles (regime analytics only)")
    p.add_argument("--chains", help="optional option-chain snapshots (contract selection)")
    p.add_argument("--label", default="UNSPECIFIED", help="data provenance label shown in every report")
    p.add_argument("--delta-source", choices=[d.value for d in DeltaSource], help="provenance of buy/sell volume columns")
    p.add_argument("--synthetic", action="store_true", help="use generated SYNTHETIC demo data")
    p.add_argument("--sessions", type=int, default=15)
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--agents", help="comma separated agent ids, e.g. A01,A02")
    p.add_argument("--mode-orch", choices=["A", "B", "C"], help="orchestrator mode")


def _cfg(args) -> AppConfig:
    cfg = load_config(args.config) if args.config else AppConfig()
    if getattr(args, "mode_orch", None):
        cfg.orchestrator.mode = args.mode_orch
    return cfg


def _agents(args):
    return [a.strip() for a in args.agents.split(",")] if args.agents else None


def cmd_synthetic(args) -> None:
    from .data.dataset import dataset_to_frame
    from .data.synthetic import generate_synthetic_dataset
    ds = generate_synthetic_dataset(sessions=args.sessions, seed=args.seed)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    dataset_to_frame(ds).to_csv(out / "options.csv", index=False)
    import pandas as pd
    rows = [{"underlying": u, "timestamp": c.ts, "open": c.open, "high": c.high, "low": c.low, "close": c.close,
             "volume": c.volume} for u, lst in ds.underlying.items() for c in lst]
    pd.DataFrame(rows).to_csv(out / "underlying.csv", index=False)
    ds.chains.to_csv(out / "chains.csv", index=False)
    (out / "README.txt").write_text("SYNTHETIC data generated by options_mas – NOT REAL MARKET DATA.\n")
    print(f"wrote SYNTHETIC dataset to {out}")


def cmd_backtest(args) -> None:
    from .backtest.engine import Backtester
    cfg = _cfg(args)
    ds = _dataset(args, cfg)
    res = Backtester(cfg, ds, _agents(args)).run()
    txt = res.to_json(include_signals=args.signals)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(txt)
        print(f"report written to {args.out}")
    o = res.report["overall"]
    print(f"DATA: {res.data_label}")
    for w in res.warnings:
        print(f"WARNING: {w}")
    print(json.dumps({"overall": o, "by_agent_and_option_type":
                      {k: {x: v[x] for x in ("total_trades", "win_rate_pct", "net_pnl", "profit_factor")}
                       for k, v in res.report["by_agent_and_option_type"].items()}}, indent=2))


def _grid(items: list[str]) -> dict:
    g = {}
    for it in items or []:
        k, v = it.split("=", 1)
        g[k] = [_val(x) for x in v.split(",")]
    return g


def cmd_walkforward(args) -> None:
    from .backtest.validation import walk_forward, walk_forward_json
    cfg = _cfg(args)
    ds = _dataset(args, cfg)
    wf = walk_forward(cfg, ds, _grid(args.grid), args.train, args.test, args.step, agents=_agents(args))
    txt = walk_forward_json(wf)
    if args.out:
        Path(args.out).write_text(txt)
    if args.ranking_out:
        Path(args.ranking_out).write_text(json.dumps(wf.ranking_table(), indent=2))
        print(f"Mode C ranking table (out-of-sample) written to {args.ranking_out}")
    print(txt)


def cmd_sensitivity(args) -> None:
    from .backtest.validation import sensitivity
    cfg = _cfg(args)
    ds = _dataset(args, cfg)
    rows = sensitivity(cfg, ds, args.param, [_val(v) for v in args.values.split(",")], _agents(args))
    print(f"DATA: {ds.label}")
    for r in rows:
        print(f"{r['param']}={r['value']!s:>8}  trades={r['total_trades']:4d}  win%={r['win_rate_pct']:6.2f}  "
              f"net={r['net_pnl']:12.2f}  PF={r['profit_factor']}  maxDD={r['max_drawdown']:.2f}")


def cmd_paper(args) -> None:
    from .agents import build_agents
    from .execution.broker import SimulatedBroker
    from .live import CandleReplayFeed, StreamingRunner
    from .storage import Store
    from .system import TradingSystem
    cfg = _cfg(args)
    cfg.execution.mode = args.mode
    if args.mode == "live":
        print("Live mode requires a real broker adapter and explicit authorisation – see docs/DEPLOYMENT.md")
        sys.exit(2)
    ds = _dataset(args, cfg)
    store = Store(args.db, run_id=f"paper-{datetime.now():%Y%m%d%H%M%S}")
    system = TradingSystem(cfg, build_agents(cfg, _agents(args)), SimulatedBroker(cfg.execution))
    system.bus.subscribe(store.handle)
    day = ds.sessions()[-1]
    keys = ds.contracts_on(day)[: args.max_contracts]
    if ds.chains is not None:  # use the contract selection agent (CE and PE independently)
        from .backtest.engine import Backtester
        keys = Backtester(cfg, ds)._select(day) or keys
    for k in keys:
        system.register_contract(ds.contracts[k], ds.warmup(k, day, cfg.backtest.warmup_sessions))
    todays = {k: ds.by_date(k)[day] for k in system.contracts}
    asyncio.run(StreamingRunner(system, CandleReplayFeed(todays, args.speed), cfg.session.timeframe_min).run())
    print(f"DATA: {ds.label} (replayed {day}) · trades: {len(system.execution.trades)} · db: {args.db}")
    for t in system.execution.trades:
        print(f"  {t.agent_id} {t.contract_key} {t.entry_price:.2f}->{t.exit_price:.2f} {t.exit_reason.value} net {t.net_pnl:.2f}")


def cmd_dashboard(args) -> None:
    import uvicorn
    from .api.server import ReplayRuntime, create_app
    from .storage import Store
    cfg = _cfg(args)
    cfg.execution.mode = "backtest"
    ds = _dataset(args, cfg)
    rt = ReplayRuntime(cfg, ds, _agents(args), speed=args.speed, store=Store(args.db, "dashboard"))
    uvicorn.run(create_app(rt), host=args.host, port=args.port)


def cmd_select(args) -> None:
    import pandas as pd
    from .contract_selection import ContractSelector
    cfg = _cfg(args)
    chains = pd.read_csv(args.chains, parse_dates=["timestamp"])
    chains["expiry"] = pd.to_datetime(chains["expiry"]).dt.date
    sel = ContractSelector(cfg.selection, {k: v.lot_size for k, v in cfg.instruments.items()},
                           {k: v.strike_step for k, v in cfg.instruments.items()})
    res = sel.select_from_snapshots(chains, args.underlying, datetime.fromisoformat(args.at))
    print(json.dumps({k.value: v.to_dict() for k, v in res.items()}, indent=2, default=str))


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(prog="options_mas")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("synthetic", help="write a SYNTHETIC demo dataset to CSV")
    p.add_argument("--out", required=True)
    p.add_argument("--sessions", type=int, default=20)
    p.add_argument("--seed", type=int, default=7)
    p.set_defaults(fn=cmd_synthetic)

    p = sub.add_parser("backtest")
    _common(p)
    p.add_argument("--out")
    p.add_argument("--signals", action="store_true", help="include all signals/decisions in the JSON report")
    p.set_defaults(fn=cmd_backtest)

    p = sub.add_parser("walkforward")
    _common(p)
    p.add_argument("--grid", nargs="*", help="dotted.param=v1,v2,...")
    p.add_argument("--train", type=int, default=8)
    p.add_argument("--test", type=int, default=4)
    p.add_argument("--step", type=int)
    p.add_argument("--out")
    p.add_argument("--ranking-out", help="write out-of-sample per-agent stats for Mode C")
    p.set_defaults(fn=cmd_walkforward)

    p = sub.add_parser("sensitivity")
    _common(p)
    p.add_argument("--param", required=True)
    p.add_argument("--values", required=True)
    p.set_defaults(fn=cmd_sensitivity)

    p = sub.add_parser("paper", help="tick-driven paper / manual-approval rehearsal on replayed candles")
    _common(p)
    p.add_argument("--mode", choices=["paper", "manual", "live"], default="paper")
    p.add_argument("--speed", type=float, default=0.0)
    p.add_argument("--max-contracts", type=int, default=6)
    p.add_argument("--db", default="options_mas.sqlite3")
    p.set_defaults(fn=cmd_paper)

    p = sub.add_parser("dashboard")
    _common(p)
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=8000)
    p.add_argument("--speed", type=float, default=0.25, help="seconds per bar during replay")
    p.add_argument("--db", default=":memory:")
    p.set_defaults(fn=cmd_dashboard)

    p = sub.add_parser("select", help="run contract selection on a chain snapshot file")
    p.add_argument("--config")
    p.add_argument("--chains", required=True)
    p.add_argument("--underlying", required=True)
    p.add_argument("--at", required=True)
    p.set_defaults(fn=cmd_select)

    args = ap.parse_args(argv)
    args.fn(args)


if __name__ == "__main__":
    main()
